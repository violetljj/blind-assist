package com.linnan.blindassist.vision

import org.junit.Assert.*
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File

class AtomPreviewPixelsTest {
    @Test fun allFourModesPreserveInputAndUseTheOpenCvPixelCoordinates() {
        val fixture = fixtureDirectory()
        val input = rgbPixels(File(fixture, "remap_input.rgb"))
        val original = input.copyOf()
        val uprightOracle = rgbPixels(File(fixture, "remap_expected.rgb"))
        val processor = AtomPreviewPixels.fromRemap(File(fixture, "atom_remap.bin").readBytes())
        assertTrue(processor.supportsUndistort)

        for (undistort in listOf(false, true)) for (enhance in listOf(false, true)) {
            val result = processor.apply(input, 640, 480, undistort, enhance)
            assertArrayEquals("Input JPEG pixels must remain intact", original, input)
            assertEquals(if (undistort) 480 else 640, result.width)
            assertEquals(if (undistort) 640 else 480, result.height)
            assertEquals(undistort, result.isUpright)
            val coordinateOracle = if (undistort) uprightOracle else original
            if (enhance) {
                assertKnownEnhancementSamples(coordinateOracle, result.pixels)
            } else {
                // The stored oracle was generated by cv2.remap + transpose, independently of Kotlin.
                assertArrayEquals("OpenCV remap/orientation parity", coordinateOracle, result.pixels)
            }
        }
    }

    @Test fun enhancementHasFixedEndpointsAndGentleMidtoneContrastWhileKeepingAlpha() {
        val input = intArrayOf(0x12000000, 0x34ffffff, 0x56808080, 0x78404040, 0x7fc0c0c0)
        val original = input.copyOf()
        val result = AtomPreviewPixels().apply(input, 5, 1, undistort = false, enhance = true)
        assertArrayEquals(intArrayOf(0x12000000, 0x34ffffff, 0x56858585, 0x78363636, 0x7fd1d1d1), result.pixels)
        assertArrayEquals(original, input)
        assertFalse(result.isUpright)
    }

    @Test fun missingCalibrationFallsBackToRawCoordinatesAndCanStillEnhance() {
        val input = intArrayOf(0xff808080.toInt(), 0xff404040.toInt(), 0xffc0c0c0.toInt())
        val processor = AtomPreviewPixels()
        assertFalse(processor.supportsUndistort)
        val raw = processor.apply(input, 3, 1, undistort = true, enhance = false)
        val enhanced = processor.apply(input, 3, 1, undistort = true, enhance = true)
        assertArrayEquals(input, raw.pixels)
        assertArrayEquals(intArrayOf(0xff858585.toInt(), 0xff363636.toInt(), 0xffd1d1d1.toInt()), enhanced.pixels)
        for (result in listOf(raw, enhanced)) {
            assertEquals(3, result.width)
            assertEquals(1, result.height)
            assertFalse(result.isUpright)
        }
    }

    @Test fun unsupportedResolutionFallsBackEvenWithValidCalibration() {
        val processor = AtomPreviewPixels.fromRemap(File(fixtureDirectory(), "atom_remap.bin").readBytes())
        val input = intArrayOf(0xff808080.toInt(), 0xff404040.toInt())
        val raw = processor.apply(input, 2, 1, undistort = true, enhance = false)
        val enhanced = processor.apply(input, 2, 1, undistort = true, enhance = true)
        assertArrayEquals(input, raw.pixels)
        assertArrayEquals(intArrayOf(0xff858585.toInt(), 0xff363636.toInt()), enhanced.pixels)
        for (result in listOf(raw, enhanced)) {
            assertEquals(2, result.width)
            assertEquals(1, result.height)
            assertFalse(result.isUpright)
        }
    }

    @Test fun truncatedRemapIsRejectedBeforeUse() {
        assertThrows(IllegalArgumentException::class.java) { AtomPreviewPixels.fromRemap(byteArrayOf(0)) }
    }

    @Test fun sameSizeButCorruptedCalibrationIsRejected() {
        val bytes = File(fixtureDirectory(), "atom_remap.bin").readBytes()
        bytes[bytes.lastIndex] = (bytes.last().toInt() xor 1).toByte()
        assertThrows(IllegalArgumentException::class.java) { AtomPreviewPixels.fromRemap(bytes) }
    }

    private fun assertKnownEnhancementSamples(before: IntArray, after: IntArray) {
        assertEquals(before.size, after.size)
        // Published curve anchors, not a second implementation of the production LUT.
        val anchors = mapOf(0 to 0, 16 to 9, 32 to 22, 64 to 54, 96 to 92, 128 to 133,
            160 to 173, 192 to 209, 224 to 237, 240 to 248, 255 to 255)
        var checked = 0
        for (i in before.indices) {
            assertEquals("Alpha at pixel $i", before[i] ushr 24, after[i] ushr 24)
            for (shift in intArrayOf(0, 8, 16)) {
                val expected = anchors[(before[i] ushr shift) and 255] ?: continue
                assertEquals("Curve sample at pixel $i, channel $shift", expected, (after[i] ushr shift) and 255)
                checked++
            }
        }
        assertTrue("The deterministic oracle must include enough curve anchor samples", checked > 1_000)
    }

    private fun rgbPixels(file: File): IntArray {
        val bytes = file.readBytes()
        assertEquals(640 * 480 * 3, bytes.size)
        return IntArray(bytes.size / 3) { i ->
            0xff000000.toInt() or ((bytes[i * 3].toInt() and 255) shl 16) or
                ((bytes[i * 3 + 1].toInt() and 255) shl 8) or (bytes[i * 3 + 2].toInt() and 255)
        }
    }

    private fun fixtureDirectory(): File {
        var directory: File? = File(System.getProperty("user.dir") ?: ".").absoluteFile
        while (directory != null) {
            val fixture = File(directory, "artifacts.local/work/mobile-fusion-integration-20261012")
            if (listOf("atom_remap.bin", "remap_input.rgb", "remap_expected.rgb").all { File(fixture, it).isFile }) {
                return fixture
            }
            directory = directory.parentFile
        }
        assumeTrue("OpenCV remap fixture unavailable; geometry parity is explicitly skipped", false)
        error("JUnit assumption should have skipped the fixture test")
    }
}
