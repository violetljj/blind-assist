def polygon(coords):
    return np.asarray([tuple(map(int, pair.split(","))) for pair in coords.split()], np.int32)


def main():
    labels_dir = OUT / "labels"
    cores_dir = OUT / "cores"
    for folder in (labels_dir, cores_dir):
        folder.mkdir(parents=True, exist_ok=True)
    sequence = json.loads((OLD / "histories.json").read_bytes())[SEQ]
    digest = sha256(",".join(str(r["rgb_ts"]) for r in sequence).encode()).hexdigest()
    if digest != "616f2885dbdf0ff92c66a5a9f14e04eda88ed19d167be309e817eafd829546b2":
        raise ValueError("RGB exposure list differs")
    manifest = dict(classes=CLASSES, return_sequence=SEQ, core_erosion_px=4,
                    upper_lip_note="Visible pale diagonal lower edge on the right; its physical attachment is uncertain.",
                    gray_box_note="Separate gray floor box with red side handle in front of stainless drinking fountain.",
                    stacked_frames_note="Stack of flat printed packages identified from later same-pass views.",
                    selection="Native RGB manual annotation; known original tube mask superposed last.",
                    frames=[])
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (9, 9))
    for row, regions in zip(sequence, REGIONS, strict=True):
        name = f"{row['rgb_ts']}.png"
        img = cv2.imread(str(DATA / name))
        tube = cv2.imread(str(OLD / "outer" / SEQ / name), cv2.IMREAD_GRAYSCALE)
        if img.shape[:2] != (428,760) or img.shape[:2] != tube.shape:
            raise ValueError(f"Incorrect image size: {name}")
        labels = np.zeros(tube.shape, np.uint8)
        for code, coords in regions:
            cv2.fillPoly(labels, [polygon(coords)], code)
        labels[tube > 0] = 1
        core = np.zeros_like(labels)
        for code in CLASSES:
            if code:
                kept = cv2.erode((labels == code).astype(np.uint8), kernel, borderType=cv2.BORDER_REPLICATE)
                core[kept > 0] = code
        counts = np.bincount(labels.ravel(), minlength=len(CLASSES)).tolist()
        if not cv2.imwrite(str(labels_dir / name), labels) or not cv2.imwrite(str(cores_dir / name), core):
            raise OSError("Cannot save native label map")
        manifest["frames"].append(dict(**row, pixels=counts, label_sha256=sha256((labels_dir / name).read_bytes()).hexdigest()))
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main()
