"""V2 repaired Development candidate-quality sweep; privileged, not camera data.

The original v2 terminal stays failed. No oracle range is used by any sweep arm.
G0 and G1 keep a9d9eabf scoring; reference_S2 is separately generated by the
unmodified original GPU2 implementation on these new sensor arrays.
"""
